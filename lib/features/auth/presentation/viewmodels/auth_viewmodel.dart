import 'dart:async';
import 'package:flutter/foundation.dart';
import 'package:studyflow/core/services/notification/app_notification.dart';
import 'package:studyflow/core/services/notification/notification_service.dart';
import 'package:studyflow/core/services/notification/notification_type.dart';
import 'package:studyflow/core/utils/safe_change_notifier.dart';
import 'package:studyflow/features/auth/domain/entities/user_entity.dart';
import 'package:studyflow/features/auth/domain/usecase/check_auth_usecase.dart';
import 'package:studyflow/features/auth/domain/usecase/login_usecase.dart';
import 'package:studyflow/features/auth/domain/usecase/logout_usecase.dart';
import 'package:studyflow/features/auth/domain/usecase/register_usecase.dart';
import 'package:studyflow/features/auth/domain/usecase/update_streak_usecase.dart';

/// Viewmodel for managing authentication state and operations.
class AuthViewmodel extends ChangeNotifier with SafeChangeNotifier {
  final RegisterUsecase registerUsecase;
  final LoginUsecase loginUsecase;
  final CheckAuthUsecase checkAuthUsecase;
  final LogoutUsecase logoutUsecase;
  final UpdateStreakUsecase updateStreakUsecase;
  StreamSubscription? _authSubscription;

  AuthViewmodel({
    required this.registerUsecase, 
    required this.loginUsecase,
    required this.checkAuthUsecase,
    required this.logoutUsecase,
    required this.updateStreakUsecase,
  }) {
    _authSubscription = checkAuthUsecase().listen((user) {
      if (user != null) {
        isAuthenticated = true;
        currentUser = user;
      } else {
        isAuthenticated = false;
        currentUser = null;
      }
      isChecking = false;
      notifyListenersSafely();
    });
  }

  @override
  void dispose() {
    _authSubscription?.cancel();
    super.dispose();
  }

  bool isLoading = false;
  bool isChecking = true;
  bool isAuthenticated = false;
  UserEntity? currentUser;

  /// Registers a new user with the given [fullName], [username], [email], and [password].
  /// 
  /// Returns an error message if the registration fails, or null if successful.
  Future<String?> Register(String fullName, String username, String email, String password) async {
    try {
      isLoading = true;
      notifyListenersSafely();

      await registerUsecase(UserEntity(
        id: '', // Will be generated by Firebase
        fullName: fullName,
        username: username, 
        email: email,
      ), password);

      NotificationService.instance.show(
        AppNotification(message: "Register Successfully!", type: NotificationType.success)
      );

      return null;
    } catch (e) {
      NotificationService.instance.show(
        AppNotification(message: "Register failed!", type: NotificationType.error)
      );
      return e.toString().replaceFirst("Exception: ", "");
    } finally {
      isLoading = false;
      notifyListenersSafely();
    }
  }

  /// Logs in a user with the given [email] and [password].
  /// 
  /// Returns an error message if the login fails, or null if successful.
  Future<String?> Login(String email, String password) async {
    try {
      isLoading = true;
      notifyListenersSafely();

      final user = await loginUsecase(
        email,
        password,
      );

      if (user == null) {
        NotificationService.instance.show(
          AppNotification(message: "Invalid credentials", type: NotificationType.error)
        );
        return "Invalid credentials";
      }
      
      NotificationService.instance.show(
        AppNotification(message: "Login Successfully", type: NotificationType.success)
      );
      return null;
    } catch (e) {
      NotificationService.instance.show(
        AppNotification(message: "Login failed", type: NotificationType.error)
      );
      return e.toString().replaceFirst("Exception: ", "");
    } finally {
      isLoading = false;
      notifyListenersSafely();
    }
  }

  /// Logs out the currently authenticated user.
  Future<void> Logout() async {
    await logoutUsecase();
    NotificationService.instance.show(
      AppNotification(message: 'Logout success', type: NotificationType.success)
    );
  }

  /// Updates the learning streak based on the task completion date.
  /// 
  /// Streak calculation logic:
  /// - If the completion date is already in the history ([streakHistory]), it is ignored (meaning if multiple tasks are done in one day, the streak is only counted once).
  /// - If there is no streak history ([lastStreakDate] == null), start a new streak = 1.
  /// - If the difference between the current completion date and the last streak date ([lastStreakDate]) is exactly 1 day,
  ///   increase the streak by 1 (maintaining a continuous streak).
  /// - If the difference is more than 1 day, the user has broken the streak, reset the streak to 1.
  /// 
  /// Finally, add the current date to the history list and call the UseCase to update the database.
  Future<void> updateStreak(DateTime completedDate) async {
    if (currentUser == null) return;
    
    final dateStr = "${completedDate.year}-${completedDate.month.toString().padLeft(2, '0')}-${completedDate.day.toString().padLeft(2, '0')}";
    
    if (currentUser!.streakHistory.contains(dateStr)) {
      return; 
    }
    
    int newStreak = currentUser!.streak;
    
    if (currentUser!.lastStreakDate != null) {
      final lastDate = currentUser!.lastStreakDate!;
      
      final dateOnlyCompleted = DateTime(completedDate.year, completedDate.month, completedDate.day);
      final dateOnlyLast = DateTime(lastDate.year, lastDate.month, lastDate.day);
      final daysDiff = dateOnlyCompleted.difference(dateOnlyLast).inDays;
      
      if (daysDiff == 1) {
        newStreak += 1;
      } else if (daysDiff > 1) {
        newStreak = 1; 
      }
    } else {
      newStreak = 1;
    }
    
    final newHistory = List<String>.from(currentUser!.streakHistory)..add(dateStr);
    
    await updateStreakUsecase(newStreak, completedDate, newHistory);
  }
}